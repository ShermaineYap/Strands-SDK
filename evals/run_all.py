"""Run every eval and write results/eval_results.json and results/EVALS.md.

    python -m evals.run_all            # offline, deterministic (~20 s)
    python -m evals.run_all --bedrock  # adds the 48 h replay with Amazon Nova (needs AWS)
"""

from __future__ import annotations

import argparse
import json
import logging
import platform
import warnings
from datetime import datetime
from pathlib import Path

from importlib.metadata import version

from . import eval_classify, eval_redteam, eval_replay, eval_verifier

OUT = Path(__file__).resolve().parent.parent / "results"


def main() -> None:
    warnings.filterwarnings("ignore")
    logging.disable(logging.CRITICAL)
    ap = argparse.ArgumentParser()
    ap.add_argument("--bedrock", action="store_true")
    args = ap.parse_args()

    c = eval_classify.run()
    v = eval_verifier.run()
    r = eval_redteam.run()
    rp = eval_replay.run()
    rp_live = eval_replay.run(bedrock=True) if args.bedrock else None

    meta = {"run_at": datetime.now().isoformat(timespec="seconds"), "python": platform.python_version(),
            "strands_agents": version("strands-agents")}
    results = {"meta": meta, "classification": c, "verifier": v, "redteam": r, "replay": rp, "replay_bedrock": rp_live}
    OUT.mkdir(exist_ok=True)
    (OUT / "eval_results.json").write_text(json.dumps(results, indent=1, default=str, ensure_ascii=False))

    va, vb = v["part_a"], v["part_b"]
    lines = [
        "# JagaSungai eval results",
        "",
        f"Run {meta['run_at']} · Python {meta['python']} · strands-agents {meta['strands_agents']} · "
        "generated by `python -m evals.run_all`",
        "",
        "| What is measured | Result | Script |",
        "|---|---|---|",
        f"| Band classification at threshold boundaries on real JPS thresholds, plus every live data fault | **{c['passed']}/{c['total']}** | `evals/eval_classify.py` |",
        f"| Injected hallucinations rejected by the verifier | **{va['caught']}/{va['total']}** | `evals/eval_verifier.py` |",
        f"| Correct paraphrases accepted (false-reject check) | **{va['controls_accepted']}/{va['controls_total']}** | `evals/eval_verifier.py` |",
        f"| Bad draft then good draft: model text survives after one retry (real Strands graph) | **{vb['retry_then_pass']}/{vb['total_each']}** | `evals/eval_verifier.py` |",
        f"| Always-bad model: graph fails closed to the template after 3 attempts | **{vb['fail_closed']}/{vb['total_each']}** | `evals/eval_verifier.py` |",
        f"| Red-team attacks on the send path blocked | **{r['blocked']}/{r['total']}** | `evals/eval_redteam.py` |",
        f"| 48 h replay: cycles that never called a model | **{rp['quiet_cycles_no_model_call']}/{rp['cycles']}** | `evals/eval_replay.py` |",
        f"| 48 h replay: briefs drafted / sent | **{rp['drafts']} / {rp['sent']}** | `evals/eval_replay.py` |",
        f"| 48 h replay: every band escalation delivered | **{'yes' if rp['every_escalation_delivered'] else 'NO'}** | `evals/eval_replay.py` |",
        f"| Graph time per cycle, offline writer (median / p95) | **{rp['graph_ms_median']} ms / {rp['graph_ms_p95']} ms** | `evals/eval_replay.py` |",
        "",
        "## Band crossings in the replay (simulated coordinator approves after 5 min)",
        "",
        "| Band | First reading at band | Minutes to draft | Minutes to delivery |",
        "|---|---|---|---|",
    ]
    for x in rp["crossings"]:
        lines.append(f"| {x['band']} | {x['first_reading_at_band']} | {x['minutes_to_draft']} | {x['minutes_to_delivery']} |")
    if rp_live:
        lines += ["", "## With Amazon Nova via Bedrock", "",
                  f"Drafts {rp_live['drafts']}, model calls {rp_live['model_calls']}, tokens in/out "
                  f"{rp_live['tokens_in']}/{rp_live['tokens_out']}, cost ≈ US${rp_live.get('cost_usd_total')} "
                  f"(≈ US${rp_live.get('cost_usd_per_draft')} per draft)."]
    else:
        lines += ["", "The replay above uses the offline scripted writer. Run `python -m evals.run_all --bedrock` "
                  "with AWS credentials to add measured Nova token counts and cost."]
    lines += ["", "## Red-team attacks", "", "| Attack | Blocked | Reason |", "|---|---|---|"]
    for x in r["rows"]:
        lines.append(f"| {x['attack']} | {'yes' if x['blocked'] else '**NO**'} | {x['reason'].replace('|', '/')} |")
    lines += ["", "## Injected hallucinations", "", "| Mutation | Rejected | First verifier error |", "|---|---|---|"]
    for x in va["rows"]:
        if "mutation" in x:
            lines.append(f"| {x['mutation']} | {'yes' if x['rejected'] else '**NO**'} | {(x['first_error'] or '').replace('|', '/')} |")
    (OUT / "EVALS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:16]))


if __name__ == "__main__":
    main()
